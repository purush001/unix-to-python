SET SERVEROUTPUT ON
SPOOL deploy_nw_audit_tbl.log

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'PS_NW_AUDIT_TBL';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE PS_NW_AUDIT_TBL (
       AUDIT_OPRID  VARCHAR2(30) NOT NULL,
       AUDIT_STAMP  DATE         NOT NULL,
       EMPLID       VARCHAR2(11) NOT NULL,
       ACTIVE_FLAG  CHAR(1)      DEFAULT ''Y'' NOT NULL)';
    DBMS_OUTPUT.PUT_LINE('Table created');
  END IF;
END;
/

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = 'PS_NW_AUDIT_TBL';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX PS_NW_AUDIT_TBL ON PS_NW_AUDIT_TBL (EMPLID, AUDIT_STAMP)';
  END IF;
END;
/

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'PS_NW_AUDIT_OLD';
  IF v_count > 0 THEN
    EXECUTE IMMEDIATE 'DROP TABLE PS_NW_AUDIT_OLD';
  END IF;
END;
/

GRANT SELECT ON PS_NW_AUDIT_TBL TO PSREADONLY;
SPOOL OFF
